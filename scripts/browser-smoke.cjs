// Uses ordinary Playwright. Set PLAYWRIGHT_MODULE only in a bundled-runtime environment.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async()=>{
  const base = process.env.DEMO_URL || 'http://127.0.0.1:8765';
  const out = path.resolve('output/screenshots'); fs.mkdirSync(out,{recursive:true});
  const browser = await chromium.launch({headless:true, channel:process.env.BROWSER_CHANNEL || 'msedge'});
  const page = await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const fixture=await page.request.get(base+'/api/offline-fixture');
  assert.equal(fixture.status(),200,'Run this script only against scripts/serve-offline-fixture.py');
  assert.equal((await fixture.json()).simulation,true,'A simulated transport is required');
  const projectName='Offline simulated UI test '+Date.now();
  const shot = name=>page.screenshot({path:path.join(out,name+'.png'),fullPage:true});
  await page.goto(base);await page.getByRole('heading',{name:'Keep terminology consistent across documents.'}).waitFor();await shot('01-workspace');
  await page.getByRole('button',{name:'Import documents',exact:true}).click();
  await page.getByLabel('Project name').fill(projectName);
  await page.getByLabel('Select PDF or DOCX files').setInputFiles(['tmp/fixtures/Protocol.pdf','tmp/fixtures/SAP.pdf']);
  await page.getByText('Review document boundaries',{exact:true}).waitFor();
  await page.getByLabel('Version and boundary review note').fill('Synthetic test pair, both Version 1.0. Not a clinical dataset.');
  await page.getByRole('checkbox').check();await shot('02-import-boundaries');
  await page.getByRole('button',{name:'Import and save originals'}).click();
  await page.getByRole('heading',{name:'Terminology register',exact:true}).waitFor();
  await page.getByRole('button',{name:'Generate AI register and links'}).click();
  await page.getByRole('status').filter({hasText:'AI run saved'}).waitFor();
  await page.getByRole('button').filter({has:page.locator('strong',{hasText:/^Arm A$/})}).click();
  await page.getByRole('checkbox',{name:/Confirm all unambiguous/}).check();
  await page.getByRole('button',{name:'Save register',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Register saved'}).waitFor();await shot('03-register-evidence');
  await page.getByRole('button',{name:'Replacement review',exact:true}).click();
  await page.getByLabel('Concept',{exact:true}).selectOption({label:'Arm A · confirmed'});
  await page.getByLabel('Replace “Arm A” with').fill('Investigational Arm A');
  await page.getByRole('button',{name:'Generate preview'}).click();
  await page.getByRole('heading',{name:'Proposed occurrences'}).waitFor();
  const checks=page.getByRole('checkbox',{name:/Approve/});
  await checks.first().check();
  const sapCheck = page.locator('.proposal').filter({hasText:'SAP · PDF p1'}).getByRole('checkbox').first();await sapCheck.check();
  await page.getByRole('checkbox',{name:/I reviewed coverage limits/}).check();await shot('04-approval-preview');
  await page.getByRole('button',{name:'Apply 2 approved changes & export'}).click();
  await page.getByRole('heading',{name:'Text-verified exports'}).waitFor({timeout:90000});
  const download = page.waitForEvent('download');await page.getByRole('link',{name:'Protocol_revised.docx',exact:true}).click();
  await (await download).saveAs(path.resolve('output/browser-Protocol_revised.docx'));await shot('05-verified-exports');
  await page.getByRole('button',{name:'Documents & coverage',exact:true}).click();await shot('06-coverage');
  await page.getByRole('button',{name:'History & transfer',exact:true}).click();
  const bundleDownload=page.waitForEvent('download');await page.getByRole('link',{name:'Export project bundle'}).click();
  const bundle=path.resolve('output/browser-project.zip');await(await bundleDownload).saveAs(bundle);await shot('07-history');
  await page.reload();await page.getByRole('button').filter({has:page.locator('strong',{hasText:projectName})}).click();
  await page.getByRole('heading',{name:'Terminology register',exact:true}).waitFor();
  await page.getByLabel('Open project bundle').setInputFiles(bundle);
  await page.getByRole('status').filter({hasText:'Project imported'}).waitFor();
  await page.setViewportSize({width:390,height:844});await shot('08-mobile');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'No page-wide mobile overflow');
  assert.deepEqual(errors,[],'No browser console or page errors');
  await browser.close();console.log('PASS OFFLINE: simulated AI generation/review, import, approvals, new DOCX export, history/transfer and mobile layout. No live model calls.');
})().catch(e=>{console.error(e);process.exit(1);});
